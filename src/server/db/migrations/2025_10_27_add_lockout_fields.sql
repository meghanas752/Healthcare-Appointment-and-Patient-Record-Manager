CREATE TABLE IF NOT EXISTS login_audit (
  id BIGINT PRIMARY KEY AUTO_INCREMENT,
  user_id BIGINT NULL,
  username VARCHAR(150) NOT NULL,
  ip VARCHAR(45) NULL,
  outcome ENUM('SUCCESS','FAIL','LOCKED') NOT NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
);
